#!/usr/bin/env python3
"""seed/stores_grit.csv -> sql/03_org_data.sql (deterministic upserts). Brand normalised to McDonald's."""
import csv, re, sys
LT = {"Freestanding":"FREESTANDING","Gas Station":"GAS_STATION","Wal*Mart":"WALMART"}
OS = {"Active":"ACTIVE","Temporarily Closed":"TEMP_CLOSED","Closed":"CLOSED"}
q = lambda s: "NULL" if s is None or s == "" else "'" + s.replace("'", "''") + "'"
b = lambda s: {"true":"true","false":"false"}[s.lower()]
slug = lambda c: re.sub(r"[^a-z0-9]+","_", re.sub(r"\s+County$","",c).lower()).strip("_")
rows = list(csv.DictReader(open("seed/stores_grit.csv")))
fix = lambda s: s.replace("McDowell's","McDonald's")
out = ["-- GENERATED by tools/gen_org_data.py from seed/stores_grit.csv. Do not hand-edit.", "BEGIN;"]
counties = sorted({r["county"] for r in rows})
out.append("INSERT INTO ref.county (county_code, name) VALUES")
out.append(",\n".join(f"  ({q(slug(c))}, {q(c)})" for c in counties))
out.append("ON CONFLICT (county_code) DO UPDATE SET name = EXCLUDED.name WHERE ref.county.name IS DISTINCT FROM EXCLUDED.name;")
terr = sorted({(r["territory_uri"], r["territory_name"]) for r in rows})
out.append("INSERT INTO org.territory (territory_id, name) VALUES")
out.append(",\n".join(f"  ({q(t)}, {q(n)})" for t, n in terr))
out.append("ON CONFLICT (territory_id) DO UPDATE SET name = EXCLUDED.name WHERE org.territory.name IS DISTINCT FROM EXCLUDED.name;")
cols = ["store_id","display_name","territory_id","restaurant_name","address","city","state_code","zip","county_code",
        "latitude","longitude","phone","operating_status_code","location_type_code","restaurant_hours","drive_thru_hours",
        "is_24_hour","has_drive_thru","has_mobile_ordering","has_delivery","has_kiosk","has_play_place"]
vals = []
for r in rows:
    v = [q(r["store_id"]), q(fix(r["label"])), q(r["territory_uri"]), q("McDonald's"), q(r["address"]), q(r["city"]),
         q(r["state"]), q(r["zip"]), q(slug(r["county"])), r["latitude"], r["longitude"], q(r["phone"]),
         q(OS[r["operating_status"]]), q(LT[r["location_type"]]), q(r["restaurant_hours"]), q(r["drive_thru_hours"]),
         *(b(r[k]) for k in ["is_24_hour","has_drive_thru","has_mobile_ordering","has_delivery","has_kiosk","has_play_place"])]
    vals.append("  (" + ", ".join(v) + ")")
out.append(f"INSERT INTO org.store ({', '.join(cols)}) VALUES")
out.append(",\n".join(vals))
upd = [c for c in cols if c != "store_id"]
out.append("ON CONFLICT (store_id) DO UPDATE SET " + ", ".join(f"{c} = EXCLUDED.{c}" for c in upd))
out.append(f"  WHERE ({', '.join('org.store.'+c for c in upd)}) IS DISTINCT FROM ({', '.join('EXCLUDED.'+c for c in upd)});")
out.append("COMMIT;")
open("sql/03_org_data.sql","w").write("\n".join(out) + "\n")
print(len(counties), "counties,", len(terr), "territories,", len(rows), "stores")
